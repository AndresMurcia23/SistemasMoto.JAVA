    private String nombreCiudad(char categoria) {
        switch (categoria) {
            case 'M':
                return "Medellín (M)";
            case 'C':
                return "Cali (C)";
            case 'I':
                return "Ibagué (I)";
            case 'B':
                return "Bogotá (B)";
            default:
                return String.valueOf(categoria);
        }
    }

