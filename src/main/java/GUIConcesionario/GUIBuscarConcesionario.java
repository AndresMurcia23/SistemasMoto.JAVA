    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String strCodigo;
        int codigo;
        Concesionario cose;

        strCodigo = txtCodigo.getText().trim();

        try {
            codigo = Integer.parseInt(strCodigo);

            Archivoconsesionario archivo = new Archivoconsesionario();
            cose = archivo.buscarcs(codigo);
            
            ArchivoMotocicletas archivoM = new ArchivoMotocicletas();

            double suma = archivoM.calcularMotos();
            String pasuma = String.valueOf(suma);
       

            if (cose != null) {
                txtTelefono.setText(String.valueOf(cose.getTelefono()));
                txtDireccion.setText(cose.getDireccion());
                txtCiudad.setText(nombreCiudad(cose.getCategoria()));
                txtCantidadMotos.setText(pasuma);

            } else {
                txtTelefono.setText("");
                txtDireccion.setText("");
                txtCiudad.setText("");
                JOptionPane.showMessageDialog(this, "Concesionario no encontrado!");
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "El código debe ser un número.");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

