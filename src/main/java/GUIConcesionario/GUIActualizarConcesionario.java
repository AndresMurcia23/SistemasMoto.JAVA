    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String textoId = txtId.getText();
        

        try {

            int codigo = Integer.parseInt(textoId);
            Archivoconsesionario archivo = new Archivoconsesionario();

            Concesionario cose = archivo.buscarcs(codigo);

            if (cose != null) {
                
                idOriginal = cose.getCodigo();
                txtTelefono.setText(String.valueOf(cose.getTelefono()));
                txtDireccion.setText(cose.getDireccion());
                txtPresupuesto.setText(String.valueOf(cose.getPresupuesto()));

                switch (cose.getCategoria()) {

                    case 'M':
                        catCategoriaCiudad.setSelectedItem("Medellín (M)");
                        break;

                    case 'C':
                        catCategoriaCiudad.setSelectedItem("Cali (C)");
                        break;

                    case 'I':
                        catCategoriaCiudad.setSelectedItem("Ibagué (I)");
                        break;

                    case 'B':
                        catCategoriaCiudad.setSelectedItem("Bogotá (B)");
                        break;
                }

            } else {
                JOptionPane.showMessageDialog(this, "Concesionario no encontrado!");
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "El código debe ser un número.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al buscar: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

