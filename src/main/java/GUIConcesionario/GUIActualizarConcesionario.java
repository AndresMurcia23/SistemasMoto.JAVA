    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed

        String textoId = txtId.getText();
        int id = Integer.parseInt(textoId);
        
        String textoTelefono = txtTelefono.getText();
        long Telefono  = Long.parseLong(textoTelefono);
        
        String textoDireccion = txtDireccion.getText();
        
        String categoriaTexto = (String) catCategoriaCiudad.getSelectedItem();
        
         char categoria = categoriaTexto.charAt(categoriaTexto.length() - 2);
         
         String textoPresupuesto = txtPresupuesto.getText();
         double presupuesto = Double.parseDouble(textoPresupuesto);
         
         Concesionario cose = new Concesionario(
                 id, Telefono,
                 textoDireccion,
                 categoria,
                 presupuesto
         );
         Archivoconsesionario arhivo = new Archivoconsesionario();

        try {
            
            arhivo.actualizarcs(idOriginal,cose);

            

            JOptionPane.showMessageDialog(
                    this,
                    "Concesionario actualizado correctamente.",
                    "Actualización",
                    JOptionPane.INFORMATION_MESSAGE
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al actualizar: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

